/** Reviewed Chinese name of a country unit or region key. */
export function areaNameZh(area: string): string | null {
  return COUNTRY_NAMES[area]?.zh ?? REGION_NAMES[area]?.zh ?? null;
}

export function countryNameZh(countryId: string): string | null {
  return COUNTRY_NAMES[countryId]?.zh ?? null;
}

export function geonamesCountryNameZh(code: string): string | null {
  const area = GEONAMES_COUNTRY_AREAS[code];
  return area ? areaNameZh(area) : null;
}

export function ghslCountryNameZh(name: string): string | null {
  const area = GHSL_COUNTRY_AREAS[name];
  return area ? areaNameZh(area) : null;
}

/** A country unit's display name; Chinese always comes from the reviewed table. */
export function displayCountryName(
  country: CountryRef,
  locale: Locale,
): string {
  return locale === 'zh'
    ? (countryNameZh(country.countryId) ?? country.name)
    : country.name;
}
